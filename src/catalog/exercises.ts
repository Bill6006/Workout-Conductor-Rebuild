export const exerciseById = new Map(
  exerciseCatalog.map((exercise) => [exercise.id, exercise]),
);

export function findExercises(query: string): Exercise[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return exerciseCatalog;
  return exerciseCatalog.filter((exercise) =>
    [exercise.name, exercise.id, ...exercise.aliases]
      .join(' ')
      .toLowerCase()
      .includes(normalized),
  );
}
