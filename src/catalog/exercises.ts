function defineExercise(seed: ExerciseSeed): Exercise {
  const mechanics = seed.mechanics ?? 'compound';
  return ExerciseSchema.parse({
    aliases: [],
    strengthSuitability: 3,
    hypertrophySuitability: 4,
    setupTimeSeconds: 45,
    transitionCost: 2,
    typicalRepRange: { min: 8, max: 12 },
    dropSet: {
      support: mechanics === 'isolation' ? 'safe' : 'conditional',
      reason:
        mechanics === 'isolation'
          ? 'Stable isolation setup supports controlled load reductions.'
          : 'Use only when fatigue will not compromise later priority work.',
    },
    superset: {
      tags: [patternTags[seed.movementPattern], 'low-setup'],
      avoidWithPatterns: [],
    },
    laterality: 'bilateral',
    mechanics,
    stabilityDemand: 3,
    gripDemand: 2,
    jointStress: [],
    considerations: {
      shoulder: 'neutral',
      knee: 'neutral',
      lowerBack: 'neutral',
    },
    commonSubstitutions: [],
    instructions: patternInstructions[seed.movementPattern],
    commonMistakes: [
      'Using momentum instead of controlling the intended range of motion.',
      'Continuing after position or joint comfort begins to deteriorate.',
    ],
    difficulty: 'intermediate',
    warmup: {
      rampEligible: mechanics === 'compound',
      minimumRampSets: mechanics === 'compound' ? 2 : 0,
      protocol: mechanics === 'compound' ? 'load-ramp' : 'none',
    },
    plateMath: {
      loadType: 'bodyweight',
      barWeightCompatible: false,
      eachHand: false,
    },
    ...seed,
    productionEnabled: true,
  });
}

